export function EmojiPicker({ onEmojiSelect, onClose }) {
  const [search, setSearch] = useState("")
  const pickerRef = useRef(null)

  useEffect(() => {
    function handleClickOutside(event) {
      if (pickerRef.current && !pickerRef.current.contains(event.target)) {
        onClose()
      }
    }
    document.addEventListener("mousedown", handleClickOutside)
    return () => document.removeEventListener("mousedown", handleClickOutside)
  }, [onClose])

  const filteredData = EMOJI_DATA.map(cat => ({
    ...cat,
    emojis: cat.emojis.filter(e => search === "" || cat.category.toLowerCase().includes(search.toLowerCase()))
  })).filter(cat => cat.emojis.length > 0)

  return (
    <motion.div
      ref={pickerRef}
      initial={{ opacity: 0, y: 10, scale: 0.95 }}
      animate={{ opacity: 1, y: 0, scale: 1 }}
      exit={{ opacity: 0, y: 10, scale: 0.95 }}
      className="absolute bottom-full mb-4 left-0 z-50 w-72 bg-white dark:bg-zinc-900 rounded-3xl shadow-2xl border border-gray-100 dark:border-zinc-800 overflow-hidden"
    >
      <div className="p-4 border-b border-gray-100 dark:border-zinc-800">
        <div className="relative">
          <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-4 h-4 text-gray-400" />
          <input
            type="text"
            placeholder="Search emojis..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            className="w-full bg-gray-50 dark:bg-zinc-800 rounded-xl py-2 pl-10 pr-4 text-xs focus:outline-none focus:ring-1 focus:ring-primary/20"
          />
        </div>
      </div>

      <div className="h-64 overflow-y-auto p-3 custom-scrollbar">
        {filteredData.map((category) => (
          <div key={category.category} className="mb-4 last:mb-0">
            <h4 className="text-[10px] font-black uppercase tracking-widest text-gray-400 mb-2 px-1">
              {category.category}
            </h4>
            <div className="grid grid-cols-7 gap-1">
              {category.emojis.map((emoji, i) => (
                <button
                  key={`${category.category}-${i}`}
                  onClick={() => {
                    onEmojiSelect(emoji)
                    // We don't necessarily want to close after every emoji, 
                    // users often want to add multiple
                  }}
                  className="w-8 h-8 flex items-center justify-center text-xl hover:bg-gray-100 dark:hover:bg-zinc-800 rounded-lg transition-colors"
                >
                  {emoji}
                </button>
              ))}
            </div>
          </div>
        ))}
      </div>
    </motion.div>
  )
}
